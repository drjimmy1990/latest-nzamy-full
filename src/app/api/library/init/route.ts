/** The whole collections list is read at once; this is only a runaway guard. */
const COLLECTIONS_MAX_ROWS = 5_000;
const MAX_TYPE_FILTER_LENGTH = 60;

export async function GET(request: Request) {
  const gate = await libraryGate();
  if (gate) return gate;

  const supabase = await createClient();
  // The laws, decrees and principles sections (locked columns; each masked
  // per tier below).
  const serverOnly = await createServiceClient();

  // Bounded reads: the front-end mounts this once on load, so cap each table
  // to a sane page size instead of `select('*')` (unbounded table scan).
  // Optional ?limit (1-200, default 50) and ?page (1-based) query params.
  // Optional ?section param to load only one section (laws|decrees|principles|books|collections).
  const { searchParams } = new URL(request.url);
  const limit = Math.min(Math.max(parseInt(searchParams.get("limit") || "50", 10) || 50, 1), 200);
  const page = Math.max(parseInt(searchParams.get("page") || "1", 10) || 1, 1);
  const section = searchParams.get("section"); // optional: load only one section
  const from = (page - 1) * limit;
  const to = from + limit - 1;

  // ── Laws filters (LIB-03): the /laws chips and doc-type row filter here, on
  // the whole table, instead of over the pages already in the browser.
  // ?section_code accepts the stored code ('06', '6') or the UI id ('SA-06').
  const rawSectionCode = searchParams.get("section_code");
  const lawSectionCode = rawSectionCode ? toSectionCode(rawSectionCode) : null;
  if (rawSectionCode && !lawSectionCode) {
    return NextResponse.json({ error: "رمز القسم غير صالح" }, { status: 400 });
  }
  const lawType = (searchParams.get("type") || "").trim();
  if (lawType.length > MAX_TYPE_FILTER_LENGTH) {
    return NextResponse.json({ error: "نوع الوثيقة غير صالح" }, { status: 400 });
  }

  // ── Paywall: read optional session + library access (guests → free tier).
  // Free users get metadata + a `locked` flag (body fields stripped); pro+ and
  // whitelisted/free items get the full row. The list page reads `free`/`locked`
  // per card to show lock icons.
  let userId: string | null = null;
  try {
    const { data: { user } } = await supabase.auth.getUser();
    userId = user?.id ?? null;
  } catch {
    userId = null;
  }
  const [{ hasFullAccess, whitelistedSlugs, freeItemsByType }, summariesReviewedOnly] = await Promise.all([
    getLibraryAccessForUser(userId),
    readSummariesReviewedOnly(),
  ]);

  // Strip large body fields from a locked row so the list never leaks paid text.
  const stripFields = (row: Record<string, unknown>, fields: string[]) => {
    for (const f of fields) if (f in row) row[f] = null;
    return row;
  };

  try {
    /**
     * Fetch one section, with a count and an explicit failure marker.
     *
     * THE MARKER, AND WHY THIS ROUTE KEEPS ITS 200. A failed section used to
     * fall through to `data: [], total: 0, hasMore: false` — logged, then
     * handed to the page as a section that genuinely holds nothing. /laws reads
     * `data.laws.data` / `.total` / `.hasMore` per section
     * (src/app/laws/page.tsx:302-312), so an unreadable «الأنظمة» rendered as a
     * library with no laws in it, next to four sections that loaded fine.
     *
     * That last part is the reason a real HTTP error is the WRONG answer here,
     * unlike the sixteen other routes in this pass: the five sections are five
     * independent reads behind one request, and a 500 would throw away four
     * good ones to report the fifth. So this follows the /api/v1/service-requests
     * compromise instead — keep the 200, mark the failure inside the envelope
     * with `degraded: true`, which listFromApi() in
     * src/lib/services/listRead.ts already maps to a failed read.
     *
     * `total` is `null`, not `0`, on failure for the same reason the empty array
     * needed a marker: an unread section has no known size, and «٠ نظام» is a
     * claim about the library rather than about the read.
     */
    // `shape` adds the section's filters and a deterministic order whose last
    // key is unique (LIB-16): offset pages over an unordered select may repeat
    // or skip rows between «تحميل المزيد» clicks.
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    type Shape = (q: any, on: ReadonlySet<string>) => any;
    type SectionRead = { data: unknown[] | null; count: number | null; error: { code?: string; message?: string } | null };
    const fetchSection = async (
      table: string,
      selectClause: string | ((on: ReadonlySet<string>) => string),
      sectionName: string,
      shape: Shape,
      client: typeof supabase | typeof serverOnly = supabase,
      // Columns pending migrations add (in the select or the order): the read
      // runs again without a feature when the database does not have it yet
      // (code deployed before the SQL). `wanted` is what this read asks for.
      optional?: { features: readonly OptionalFeature[]; wanted: readonly string[] }
    ) => {
      const { data, count, error } = await readWithOptionalFeatures<SectionRead>(
        (on) => shape(
          client
            .schema("library")
            .from(table)
            .select(typeof selectClause === "string" ? selectClause : selectClause(on), { count: "exact" }),
          on,
        ).range(from, to),
        optional?.features ?? [],
        optional?.wanted ?? [],
      );

      if (error) {
        console.error(`[Library Init API] ${sectionName} error:`, error);
        return {
          data: [] as unknown[],
          total: null,
          hasMore: false,
          page,
          limit,
          degraded: true,
        };
      }

      const total = count ?? 0;
      const items = data || [];
      return {
        data: items,
        total,
        hasMore: from + items.length < total,
        page,
        limit,
        degraded: false,
      };
    };

    // Only fetch requested section(s)
    const shouldFetch = (s: string) => !section || section === s;

    /**
     * The stand-in for a section `?section=` did not ask for. It is neither a
     * failure nor a real read, and `notRequested` says which — without it this
     * envelope is byte-identical to "this section is empty", and the only thing
     * keeping that from being read as one is that /laws happens to only look at
     * the single section it asked for. A caller that iterated all five would be
     * told the library is empty by a route that never queried it.
     *
     * A FACTORY, not a shared constant. It used to be one object handed to up
     * to four sections at once, and the paywall block below assigns straight
     * into `<section>.data` — so those four aliased the same object and wrote
     * over each other. Harmless while every write was `[]`, but the moment a
     * per-section field exists (this `notRequested`, `degraded`, a future
     * count) one section's value silently becomes all of theirs.
     */
    const emptySection = () => ({
      data: [] as unknown[],
      total: null,
      hasMore: false,
      page: 1,
      limit,
      degraded: false,
      notRequested: true,
    });

    /**
     * Collections are read WHOLE (LIB-08): the index had no «تحميل المزيد» for
     * them, so 159 of 209 were unreachable. The list is small (card columns
     * only, no `metadata`), and a second load-more button beside the
     * principles one would be ambiguous. selectAllPages walks past PostgREST's
     * 1,000-row cap should the table ever grow that far. Page 2+ returns an
     * empty page so an old client's load-more cannot duplicate rows.
     */
    const fetchAllCollections = async () => {
      if (page > 1) {
        return { data: [] as unknown[], total: null, hasMore: false, page, limit, degraded: false };
      }
      const { data, error } = await selectAllPages<Record<string, unknown>>(
        (f, t) =>
          supabase
            .schema("library")
            .from("judicial_collections")
            .select(COLLECTION_LIST_COLUMNS)
            .order("title")
            .order("id")
            .range(f, t) as unknown as PromiseLike<{ data: Record<string, unknown>[] | null; error: { message: string } | null }>,
        { pageSize: 1000, maxRows: COLLECTIONS_MAX_ROWS }
      );
      if (error) {
        console.error("[Library Init API] collections error:", error);
        return { data: [] as unknown[], total: null, hasMore: false, page, limit, degraded: true };
      }
      return { data: data as unknown[], total: data.length, hasMore: false, page, limit: data.length, degraded: false };
    };

    const [laws, decrees, principles, books, collections] = await Promise.all([
      shouldFetch("laws")
        ? fetchSection("laws", (on) => `${on.has("summary") ? `${LAW_LIST_COLUMNS}, ${LAW_SUMMARY_COLUMN}` : LAW_LIST_COLUMNS}, ${LAW_EVENT_DATE_SELECT}` + (on.has("mergedNames") ? `, ${LAW_MERGED_NAMES_COLUMN}` : "") + (on.has("mergedDetails") ? `, ${LAW_MERGED_DETAILS_COLUMN}` : "") + (on.has("summaryStatus") ? ", summary_status" : ""), "laws", (q, on) => {
            let out = q;
            if (lawSectionCode) out = out.eq("section_code", lawSectionCode);
            if (lawType) {
              // The executive-regulation filter also lists laws that carry a
              // merged regulation (the page's sub_types rule). The `.or()`
              // string is a fixed literal — user input only ever reaches `.eq`.
              out = lawType === EXEC_REGULATION_TYPE
                ? out.or(`type.eq."${EXEC_REGULATION_TYPE}",has_merged_regulation.is.true`)
                : out.eq("type", lawType);
            }
            // N2.5 (see LAW_SORT_KEY): merged → newest of (amendment, issue), in SQL.
            // Owner ٣١٧ / note ١٢ item ٨ (LAW_REPEALED_KEY): in force before repealed, first.
            if (on.has("sort")) {
              if (on.has("repealedLast")) out = out.order(LAW_REPEALED_KEY, ASC_NULLS_LAST);
              return out
                .order("has_merged_regulation", DESC_NULLS_LAST)
                .order(LAW_SORT_KEY, DESC_NULLS_LAST)
                .order("title")
                .order("slug");
            }
            // Before 20261025_40: section, then title (the chip order).
            return out.order("section_code").order("title").order("slug");
          }, serverOnly, {
            features: LAW_OPTIONAL_FEATURES,
            // The موجز for the viewers the ٢٦٠ flag admits (answered: everyone,
            // the guest too); the order for all.
            // The «يشتمل على» names for every viewer (cleaned per tier below).
            wanted: [...(lawSummaryVisible(hasFullAccess) ? ["summary", "summaryStatus", "sort", "repealedLast"] : ["sort", "repealedLast"]), "mergedNames", "mergedDetails"],
          })
        : Promise.resolve(emptySection()),
      shouldFetch("decrees")
        ? fetchSection(
            "decrees_circulars",
            (on) => (on.has("decreeSummaryStatus") ? `${DECREE_LIST_COLUMNS}, summary_status` : DECREE_LIST_COLUMNS),
            "decrees",
            (q) => q.order("id"),
            serverOnly,
            { features: DECREE_OPTIONAL_FEATURES, wanted: ["decreeSummaryStatus"] },
          )
        : Promise.resolve(emptySection()),
      // Service role: principles.text is server-only since 20261016_01 (owner
      // decision ١٧١); the paywall block below strips it from locked rows.
      shouldFetch("principles")
        ? fetchSection(
            "principles",
            `id, principle_number, issuing_body, text, session_date, decision_number, year_hijri,
             judicial_collections ( id, title, court, track, source_id )`,
            "principles",
            (q) => q.order("id"),
            serverOnly
          )
        : Promise.resolve(emptySection()),
      shouldFetch("books")
        ? fetchSection(
            "feqh_books",
            // Owner ٢٦٢: the series pair when the database has it (20261026_51).
            (on) => bookVolumeColumns(on, BOOK_LIST_COLUMNS),
            "books",
            (q) => q.order("title").order("id"),
            supabase,
            { features: [BOOK_SERIES_FEATURE], wanted: [BOOK_SERIES_FEATURE.key] },
          )
        : Promise.resolve(emptySection()),
      shouldFetch("collections")
        ? fetchAllCollections()
        : Promise.resolve(emptySection()),
    ]);

    // ── Apply paywall per row (add free/locked; strip body fields for locked) ──
    // T28-22 (owner decision): the issuing decree and its date are for
    // subscribers (tier pro+, never the whitelist — the same rule as the law
    // page). A non-subscriber's rows carry null there; `status` stays.
    const lawsRows = laws.data as unknown as Record<string, unknown>[];

    // §2.4-1 (owner package 2026-11-02): the law that replaced each repealed
    // law on this page, for the card's link next to «ملغى». The link is on the
    // NEWER law (supersedes_law_slug), read like the law page's `replacedBy`
    // (/api/library/laws/[slug]) with the request client — slug, title and
    // supersedes_law_slug are on the anon allow-list of 20261004_01. ONE read
    // of the few laws that name a predecessor (the column is mostly empty),
    // one request when its count is covered and paged by selectAllPages
    // otherwise (S5-B12), only when this page has a repealed law — no `.in()`
    // list in the URL. Supplementary: a failed lookup only means no link on
    // the card.
    let successorRows: unknown[] = [];
    if (lawsRows.some((row) => isRepealedLawStatus(row.status))) {
      try {
        const { data, error } = await readSuccessorRows(
          () =>
            supabase
              .schema("library")
              .from("laws")
              .select("slug,title,supersedes_law_slug", { count: "exact" })
              .not("supersedes_law_slug", "is", null)
              .order("slug")
              .range(0, 999) as unknown as PromiseLike<{ data: Record<string, unknown>[] | null; error: { message: string } | null; count: number | null }>,
          () =>
            selectAllPages<Record<string, unknown>>(
              (f, t) =>
                supabase
                  .schema("library")
                  .from("laws")
                  .select("slug,title,supersedes_law_slug")
                  .not("supersedes_law_slug", "is", null)
                  .order("slug")
                  .range(f, t) as unknown as PromiseLike<{ data: Record<string, unknown>[] | null; error: { message: string } | null }>,
              { pageSize: 1000, maxRows: SUCCESSOR_READ_MAX_ROWS }
            )
        );
        if (error) console.warn("[Library Init API] successor lookup failed:", error.message);
        else successorRows = data;
      } catch (e) {
        console.warn("[Library Init API] successor lookup threw:", e);
      }
    }
    const successors = successorsBySupersededSlug(successorRows);

    // Library agent §1.8 (batch l10): «+N تشريعات فرعية» on the card — the
    // documents whose parent_law_id names a card's instrument_id, by the same
    // rule as the law page's list (isLawChildOf in _children.ts), less the ones
    // whose title is one of the card's merged names (file 16 §7 counts both
    // kinds; the card adds the merged names itself). The names are compared in
    // both forms (a subscriber's and a guest's), so every viewer gets the same
    // number. One read per
    // chunk of this page's ids (≤ 50 per `in (…)`, so ≤ 4 for the largest
    // page), served by laws_parent_law_id_lookup_idx (20261130_20); slug and
    // parent_law_id are on the anon allow-list of 20261004_01, so the request
    // client reads them. Supplementary: a failed read only means no counter.
    let childCounts = new Map<string, number>();
    // File 03 L3 (batch l12): the first linked-child titles for the card.
    let childTitles = new Map<string, string[]>();
    const childChunks = childKeyChunks(lawsRows);
    if (childChunks.length > 0) {
      try {
        const reads = await Promise.all(childChunks.map((keys) =>
          readSuccessorRows(
            () =>
              supabase
                .schema("library")
                .from("laws")
                .select("slug,title,parent_law_id", { count: "exact" })
                .in("parent_law_id", keys)
                .order("slug")
                .range(0, 999) as unknown as PromiseLike<{ data: Record<string, unknown>[] | null; error: { message: string } | null; count: number | null }>,
            () =>
              selectAllPages<Record<string, unknown>>(
                (f, t) =>
                  supabase
                    .schema("library")
                    .from("laws")
                    .select("slug,title,parent_law_id")
                    .in("parent_law_id", keys)
                    .order("slug")
                    .range(f, t) as unknown as PromiseLike<{ data: Record<string, unknown>[] | null; error: { message: string } | null }>,
                { pageSize: 1000, maxRows: SUCCESSOR_READ_MAX_ROWS }
              )
          )
        ));
        const failed = reads.find((r) => r.error);
        if (failed) console.warn("[Library Init API] children count failed:", failed.error?.message);
        else {
          const childRows = reads.flatMap((r) => r.data);
          const parents = lawsRows.map((row) => ({
            slug: row.slug,
            instrument_id: row.instrument_id,
            title: row.title,
            mergedNames: [true, false].flatMap((subscriber) => [
              ...mergedNamesFromDetails(row[LAW_MERGED_DETAILS_COLUMN], subscriber),
              ...mergedNamesForViewer(row[LAW_MERGED_NAMES_COLUMN], subscriber),
            ]),
          }));
          childCounts = childCountsByParent(childRows, parents);
          childTitles = childTitlesByParent(childRows, parents);
        }
      } catch (e) {
        console.warn("[Library Init API] children count threw:", e);
      }
    }

    laws.data = lawsRows.map((row) => {
      const slug = row.slug as string;
      const isFree = isFreeLibraryItem({ contentType: "laws", itemId: slug, hasFullAccess, freeItemsByType, whitelistedLawSlugs: whitelistedSlugs });
      const replacedBy = isRepealedLawStatus(row.status) ? successors.get(slug) : undefined;
      // Owner ٣١٨: the one public date, from the UNMASKED row (the mask below
      // nulls issue_date_hijri for a non-subscriber) — the date alone.
      const event = latestLegislativeEvent({
        latest_update: { date_hijri: row[LAW_EVENT_DATE_ALIAS] },
        issue_date_hijri: row.issue_date_hijri,
      });
      // §1.8 (l10): the card's sub-legislation count (childCounts above).
      const childCount = childCounts.get(slug) ?? 0;
      const { [LAW_EVENT_DATE_ALIAS]: _eventDate, ...rest } = row;
      void _eventDate; // never sent: the raw latest_update date leaves only as `latest_legislative_update`
      const shaped = isFree ? rest : stripFields({ ...rest }, ["preamble", "description", "article_status_summary"]);
      // Q96 (batch l12): the card's موجز only when the law's summary is
      // reviewed (library_summaries_reviewed_only); the status never leaves.
      const lawSummaryShown = summaryShown(shaped.summary_status, summariesReviewedOnly);
      delete shaped.summary_status;
      if (!lawSummaryShown && "summary_brief" in shaped) shaped.summary_brief = null;
      // Owner ٣١٩ (ب): the موجز stays for everyone; a non-subscriber's loses
      // its decree numbers and issue dates here, on the server.
      if (typeof shaped.summary_brief === "string") {
        shaped.summary_brief = summaryForViewer(shaped.summary_brief, hasFullAccess) || null;
      }
      // Owner 2026-11-07: the «يشتمل على» names, cleaned for a non-subscriber.
      // Owner 2026-11-06 item 4: the file's own names first (merged_regulations),
      // the regulation-ref names when it lists none. The jsonb never leaves.
      if (LAW_MERGED_NAMES_COLUMN in shaped || LAW_MERGED_DETAILS_COLUMN in shaped) {
        const fromDetails = mergedNamesFromDetails(shaped[LAW_MERGED_DETAILS_COLUMN], hasFullAccess);
        shaped[LAW_MERGED_NAMES_COLUMN] = fromDetails.length
          ? fromDetails
          : mergedNamesForViewer(shaped[LAW_MERGED_NAMES_COLUMN], hasFullAccess);
        delete shaped[LAW_MERGED_DETAILS_COLUMN];
      }
      // instrument_id is read only to count the sub-legislation; it is not a card field.
      delete shaped.instrument_id;
      return {
        ...maskListOfficialFields(shaped, hasFullAccess),
        ...(event ? { latest_legislative_update: event.dateHijri } : {}),
        // §2.4-1: {slug, title} of the law that replaced a repealed one.
        ...(replacedBy ? { replaced_by: replacedBy } : {}),
        // §1.8 (l10): how many documents name this one in parent_law_id; absent at 0.
        ...(childCount > 0 ? { sub_legislation_count: childCount } : {}),
        // File 03 L3 (batch l12): their first titles (public, like the catalogue).
        ...((childTitles.get(slug)?.length ?? 0) > 0 ? { sub_legislation_titles: childTitles.get(slug) } : {}),
        free: isFree,
        locked: !isFree,
      };
    }) as any;

    const decreesRows = decrees.data as unknown as Record<string, unknown>[];
    decrees.data = decreesRows.map((row) => {
      const isFree = hasFullAccess || ((freeItemsByType.decrees as string[]) ?? []).includes(row.id as string);
      // Owner ٢٦٣ (and ٢٦٠'s rule for the laws): the موجز is for everyone —
      // a locked card keeps summary_brief / summary (the decree route sends
      // both to every viewer too); only the text stays out.
      // Owner ٤٢٤ / ٣٨٠: the number and date are a subscriber's (hasFullAccess,
      // never the free-item list) — '' for everyone else, like the decree route.
      const shaped = isFree ? { ...row } : stripFields({ ...row }, ["content", "text"]);
      // Q96 (batch l12): a decree's summaries only once reviewed; the status never leaves.
      const decreeSummaryShown = summaryShown(shaped.summary_status, summariesReviewedOnly);
      delete shaped.summary_status;
      if (!decreeSummaryShown) for (const key of ["summary_brief", "summary"]) if (key in shaped) shaped[key] = null;
      // ...and the موجز / summary lose their numbers and dates (the laws' ٣١٩ rule).
      for (const key of ["summary_brief", "summary"]) {
        if (typeof shaped[key] === "string") shaped[key] = summaryForViewer(shaped[key] as string, hasFullAccess);
      }
      // Owner Q101 (batch l12): ...and the title loses them too (decreeTitleForViewer).
      shaped.title = decreeTitleForViewer({ title: row.title, type: row.type, summary: shaped.summary_brief || shaped.summary }, hasFullAccess);
      return { ...maskDecreeOfficialFields(shaped, hasFullAccess), free: isFree, locked: !isFree };
    }) as any;

    const principlesRows = principles.data as unknown as Record<string, unknown>[];
    principles.data = principlesRows.map((row) => {
      const isFree = isFreeLibraryItem({ contentType: "principles", itemId: row.id as string, hasFullAccess, freeItemsByType, whitelistedLawSlugs: whitelistedSlugs });
      const out = isFree ? { ...row } : stripFields({ ...row }, ["text"]);
      return { ...out, free: isFree, locked: !isFree };
    }) as any;

    // Books + collections are metadata (table-of-contents level); the gated
    // content is in feqh_blocks / principles, so the list is free to browse.
    books.data = (books.data as unknown as Record<string, unknown>[]).map((row) => ({ ...row, free: true, locked: false })) as any;
    collections.data = (collections.data as unknown as Record<string, unknown>[]).map((row) => ({ ...row, free: true, locked: false })) as any;

    // Q100a (batch l12): the non-subscriber list cap — 30 items a day / 100 a
    // week, SHIPPED OFF until the owner approves the evidence
    // (publicListCapServer.ts; fails open). Items are allowed in the order
    // listed; a section that was cut says hasMore: false, and the answer
    // carries `listLimit` with the reader's message.
    const LIST_SECTIONS = [
      [laws, "law", "slug"],
      [decrees, "decree", "id"],
      [principles, "principle", "id"],
      [books, "book", "id"],
      [collections, "collection", "id"],
    ] as const;
    const listCap = await spendPublicListItems(
      request,
      { userId, hasFullLibrary: hasFullAccess },
      LIST_SECTIONS.flatMap(([s, kind, idField]) =>
        (s.data as unknown as Record<string, unknown>[]).map((row) => listItemKey(kind, row[idField])).filter((k): k is string => k !== null),
      ),
    );
    if (listCap.allowed) {
      for (const [s, kind, idField] of LIST_SECTIONS) {
        const rows = s.data as unknown as Record<string, unknown>[];
        const kept = keepAllowed(rows, (row) => listItemKey(kind, row[idField]), listCap.allowed);
        if (kept.length < rows.length) {
          s.data = kept as any;
          s.hasMore = false;
        }
      }
    }

    return NextResponse.json(
      {
        laws,
        decrees,
        principles,
        books,
        collections,
        // T28-22: true when laws[].issuing_instrument / issue_date_hijri were
        // withheld from this viewer (non-subscriber), so the page can say
        // «للمشتركين» instead of «—». Owner ٤٢٤: decrees[].ref / date too.
        officialMetaLocked: !hasFullAccess,
        // The viewer's own full-library flag (a Pro+ tier, an active library
        // grant, or an admin; owner ٢٠٥/٢٠٩). /laws hands it to its tabs, so a
        // card's lock follows this rule, not the client's tier-only gate.
        viewer: { hasFullAccess },
        // Q100a: present only when the list cap held items back.
        ...(listCap.notice ? { listLimit: listCap.notice } : {}),
        // File 03 L3 / library question 5 (batch l12): a sub-legislation's
        // name under a card in full or short (admin setting library_reader_display).
        display: { childNameForm: (await loadLibraryReaderDisplay()).child_name_form },
      },
      // Tier-shaped (paywall + official metadata): never from a shared cache.
      { headers: { "Cache-Control": TIER_SHAPED_CACHE_CONTROL } },
    );
  } catch (error) {
    console.error("[Library Init API] Error:", error);
    return NextResponse.json({ error: "تعذّر تحميل المكتبة القانونية" }, { status: 500 });
  }
}
