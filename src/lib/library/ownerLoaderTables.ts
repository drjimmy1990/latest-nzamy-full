export interface ProbeResult {
  error: { message?: string; code?: string } | null;
}

export interface PreflightProblem {
  table: string;
  column: string;
  reason: string;
}

/**
 * Probe every required column of `tables` (one tiny read each). Any error is a
 * problem — not only "column does not exist": a permission error or a timeout
 * means the column's presence is unknown, and loading would risk the silent
 * loss note ١١ forbids. A probe that throws is a problem too.
 */
export async function preflightRequiredColumns(
  tables: readonly OwnerLoaderTable[],
  probe: (table: string, column: string) => PromiseLike<ProbeResult>,
): Promise<PreflightProblem[]> {
  const problems: PreflightProblem[] = [];
  for (const t of tables) {
    for (const column of t.requiredColumns ?? []) {
      try {
        const { error } = await probe(t.name, column);
        if (error) problems.push({ table: t.name, column, reason: error.message || error.code || "unknown error" });
      } catch (e) {
        problems.push({ table: t.name, column, reason: e instanceof Error ? e.message : String(e) });
      }
    }
  }
  return problems;
}

/** An RPC batch is stored only when the RPC answered exactly the batch's row count. */
export function rpcBatchStored(batchLength: number, data: unknown, error: unknown): boolean {
  if (error) return false;
  const stored = typeof data === "number" ? data : Number(data);
  return Number.isFinite(stored) && stored === batchLength;
}
