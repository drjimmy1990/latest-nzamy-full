/**
 * ownerLoaderTables — the tables scripts/seed-library-from-owner.mjs loads,
 * and the checks it makes before writing any of them (owner note ١١,
 * 2026-10-26, re-sent 2026-10-30).
 *
 * The library is FIFTEEN tables (note ١١ §١ — no sixteenth "presentation"
 * table): five for laws, two for decrees, four for precedents (the fourth is
 * library_precedent_private.precedent_unparsed_details, reached only through
 * public.store_private_precedent_details), four for feqh books. The loader
 * knew fourteen: private_precedent_details.jsonl, which seed-library.ts
 * writes through the RPC, was ignored (note ١١ §٢ item ٣).
 *
 * Fail closed (note ١١ §٢ item ٢): feqh_books.series_id / volume_number
 * (20261026_51) used to be "optional" — probed, and silently stripped from
 * every row when the probe said missing, so a load before the SQL (or a probe
 * that timed out) lost every book's series. They are now REQUIRED: before the
 * first write, preflightRequiredColumns probes each required column, and ANY
 * failure — a missing column, a permission error, a timeout — stops the run
 * with exit 1, before a single row is written.
 *
 * Pure (the probe is passed in): `node --test` loads it directly; nothing here
 * opens a connection.
 */

export interface OwnerLoaderTable {
  /** The file is `<name>.jsonl` in the --rows folder. */
  name: string;
  pkey: string;
  batchSize: number;
  /** Keys dropped from every row before the write. */
  stripKeys: readonly string[];
  /** Columns the database must have before anything is written (preflight). */
  requiredColumns?: readonly string[];
  /**
   * Written through this RPC (in `rpcSchema`) instead of an upsert into
   * library.<name>; the RPC must answer the batch's row count.
   */
  rpc?: { name: string; schema: string; arg: string };
  /** A missing file is normal (not every export has it) and does not fail the run. */
  optionalFile?: boolean;
}

